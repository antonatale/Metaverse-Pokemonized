/* Writes src/data/panorama-coast.ts: the coast of Formia from OpenStreetMap (tools/formia/osm-extract.json), from the
   tip of Gaeta round the gulf to the mouth of the Garigliano, thinned to about 15 m, for the panoramas of the belvederi
   (render/canvas/panorama.ts). Map data © OpenStreetMap contributors (ODbL 1.0).   npx tsx tools/panorama/coast.ts */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
type LL = [number, number];
const here = path.dirname(fileURLToPath(import.meta.url));
const osm = JSON.parse(fs.readFileSync(path.join(here, '../formia/osm-extract.json'), 'utf8')) as { coast: LL[][] };
/* the inner coast of Gaeta (from its tip to Vindicio), then Vindicio to the Garigliano */
const gaeta = osm.coast.find((c) => Math.abs(c[0][0] - 41.20706) < 1e-4)!, gulf = osm.coast.find((c) => c.length > 1000)!;
const line = gaeta.concat(gulf.slice(1));
const kx = Math.cos(41.25 * Math.PI / 180);
function dist(p: LL, a: LL, b: LL) {
  const ax = a[1] * kx, ay = a[0], bx = b[1] * kx, by = b[0], px = p[1] * kx, py = p[0];
  const dx = bx - ax, dy = by - ay, l = dx * dx + dy * dy, t = l ? Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / l)) : 0;
  return Math.hypot(px - ax - t * dx, py - ay - t * dy);
}
function simplify(pts: LL[], eps: number): LL[] {
  if (pts.length < 3) return pts;
  let best = 0, at = 0;
  for (let i = 1; i < pts.length - 1; i++) { const d = dist(pts[i], pts[0], pts[pts.length - 1]); if (d > best) { best = d; at = i; } }
  if (best < eps) return [pts[0], pts[pts.length - 1]];
  return simplify(pts.slice(0, at + 1), eps).slice(0, -1).concat(simplify(pts.slice(at), eps));
}
const out = simplify(line, 0.00014).map((p) => [Math.round(p[0] * 1e5) / 1e5, Math.round(p[1] * 1e5) / 1e5]);
fs.writeFileSync(path.join(here, '../../src/data/panorama-coast.ts'),
  '/* Generated by tools/panorama/coast.ts from OpenStreetMap (© OpenStreetMap contributors, ODbL 1.0). Do not edit by hand.\n' +
  '   The coast from the tip of Gaeta, round the gulf of Formia, to the mouth of the Garigliano: [lat, lon] */\n' +
  'export const GULF_COAST: [number, number][] = ' + JSON.stringify(out) + ';\n');
console.log('coast:', line.length, '→', out.length, 'points');
