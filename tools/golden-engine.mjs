/* Writes tests/fixtures/engine-golden.json from the ORIGINAL engine, the one inside legacy/index.html.
   The fixture is what the engine is checked against (npm test), also after legacy/index.html is gone.
   Run: node tools/golden-engine.mjs */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { scenarios, digest, staticFacts } from '../tests/engine/scenarios.mjs';
import { legacyEngine } from '../tests/engine/legacy.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const E = legacyEngine();
if (!E) { console.error('legacy/index.html is gone: the golden file can no longer be regenerated'); process.exit(1); }
const list = scenarios();
const out = {
  note: 'Generated by tools/golden-engine.mjs from the engine in legacy/index.html. Do not edit by hand.',
  facts: createHash('sha256').update(JSON.stringify(staticFacts(E))).digest('hex').slice(0, 24),
  battles: {}
};
for (const sc of list) out.battles[sc.key] = digest(E, sc);
fs.mkdirSync(path.join(root, 'tests/fixtures'), { recursive: true });
fs.writeFileSync(path.join(root, 'tests/fixtures/engine-golden.json'), JSON.stringify(out, null, 1) + '\n');
console.log('wrote', list.length, 'battles');
