/* Writes the golden files from the ORIGINAL game, the scripts inside legacy/index.html:
     tests/fixtures/engine-golden.json    2040 deterministic battles of the battle engine
     tests/fixtures/sprites-golden.json   every SVG string the portrait module hands out
     tests/fixtures/canvas-golden.json    every canvas call the map art makes
   They are what npm test checks the new code against, also after legacy/index.html is gone.
   Run: npm run golden (only while legacy/index.html exists) */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { scenarios, digest, staticFacts } from '../tests/golden/scenarios.mjs';
import { spriteDigests } from '../tests/golden/sprites.mjs';
import { canvasDigests } from '../tests/golden/canvas.mjs';
import { MAPS, LEGEND } from '../src/data/maps';
import { legacyEngine, legacyGlobals } from '../tests/golden/legacy.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const E = legacyEngine();
if (!E) { console.error('legacy/index.html is gone: the golden files can no longer be regenerated'); process.exit(1); }
const write = (name, data) => {
  fs.mkdirSync(path.join(root, 'tests/fixtures'), { recursive: true });
  fs.writeFileSync(path.join(root, 'tests/fixtures', name), JSON.stringify(data, null, 1) + '\n');
};

const list = scenarios();
const engine = {
  note: 'Generated by tools/golden.mjs from the engine in legacy/index.html. Do not edit by hand.',
  facts: createHash('sha256').update(JSON.stringify(staticFacts(E))).digest('hex').slice(0, 24),
  battles: {}
};
for (const sc of list) engine.battles[sc.key] = digest(E, sc);
write('engine-golden.json', engine);

const SPR = legacyGlobals('/* Sprites v2').SPR;
write('sprites-golden.json', { note: 'Generated by tools/golden.mjs from the sprites in legacy/index.html: sha256 and length of each string.', strings: spriteDigests(SPR) });
const ART = legacyGlobals('/* World art:').WORLD_ART;
const canvas = canvasDigests(ART, MAPS, LEGEND);
write('canvas-golden.json', { note: 'Generated by tools/golden.mjs from the map art in legacy/index.html: sha256 of each call log, and its length.', calls: canvas });
console.log('wrote', list.length, 'battles,', Object.keys(spriteDigests(SPR)).length, 'sprite strings,', Object.keys(canvas).length, 'canvas drawings');
